        public static bool IsDlcGoods(int id) => DlcGoods.Contains(id);

        public static bool IsDlcWeapon(int id) => id >= 23000000 || id / 100000 == 191;

        public static bool IsDlcArmor(int id) => id is >= 40000 and <= 43000 or >= 330000 and <= 430000;

        public static bool IsDlcBoss(SaveBoss boss) => boss.Defeated >= 13400000;

        public static bool IsDlcLamp(int flag) => flag >= 73400000;

        public static BossState State(SaveSlot slot, SaveBoss boss) => slot.Flag(boss.Defeated) ? BossState.Defeated : BossState.Alive;

        public static void MarkDefeated(SaveSlot slot, SaveBoss boss)
        {
            slot.SetFlag(boss.Defeated, true);
            foreach (var flag in boss.DefeatOn) slot.SetFlag(flag, true);
            foreach (var flag in boss.DefeatOff) slot.SetFlag(flag, false);
        }

        public static void FightAgain(SaveSlot slot, SaveBoss boss)
        {
            slot.SetFlag(boss.Defeated, false);
            foreach (var flag in boss.FightFlags) slot.SetFlag(flag, false);
        }

        public static void LockAgain(SaveSlot slot, SaveBoss boss)
        {
            FightAgain(slot, boss);
            foreach (var flag in boss.LockFlags) slot.SetFlag(flag, false);
        }
